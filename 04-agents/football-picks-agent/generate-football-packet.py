#!/usr/bin/env python3
"""generate-football-packet.py — ~1.5K-token domain packet (AQ-133 pattern).

    python3 -B 04-agents/football-picks-agent/generate-football-packet.py

Sessions read this first instead of 9K+ of instructions/config. Regenerated
by the daily loop; do not hand-edit.
"""
from __future__ import annotations
import csv, pathlib, sys
AGENT = pathlib.Path(__file__).resolve().parent
ROOT = AGENT.parents[1]
sys.path.insert(0, str(ROOT / "04-agents" / "lib"))
from davidos_lib import now_eastern  # noqa: E402
from football_performance import latest_complete_main_card, latest_recommendations  # noqa: E402
OUT = ROOT / "00-system" / "context-packets" / "football-packet.md"

def record():
    rows = list(csv.DictReader((AGENT / "recommendation-ledger.csv").open(encoding="utf-8")))
    rows = latest_recommendations(rows)
    w = sum(1 for r in rows if r.get("result") == "W")
    l = sum(1 for r in rows if r.get("result") == "L")
    p = sum(1 for r in rows if r.get("result") == "PUSH")
    pend = sum(1 for r in rows if not r.get("result"))
    return w, l, p, pend

def main() -> int:
    w, l, p, pend = record()
    stamp = now_eastern()
    recs = list(csv.DictReader((AGENT / "recommendation-ledger.csv").open(encoding="utf-8")))
    main_card = latest_complete_main_card(recs, stamp.date())
    main_record = main_card["record"]
    OUT.write_text(f"""# Football packet — generated {stamp.strftime('%Y-%m-%d %H:%M ET')}

> Regenerated by the daily loop; do not hand-edit. Full detail: grep
> `04-agents/football-picks-agent/` (instructions, model-notes,
> staking-config) and `03-projects/football-picks-agent/` (format spec,
> dry-run protocol, data roadmap).

## Main-ten learning record
Latest complete ten-pick card: **{main_card['main_card_date'] or 'not recorded'}**.
**{main_record['w']}-{main_record['l']}** · {main_record['pending']} pending.
Track the latest complete main ten each week at original lines and confidence;
later short cards and manual leans stay separate. Review market and confidence
cohorts before proposing changes. Contract: `dashboard-metrics.md`.

## Broader season recommendation audit (unique selections; latest valid line)
**{w}-{l}{f'-{p}' if p else ''}** · {pend} pending · breakeven 52.4% at -110.
Confidence v2 since Week 2 (movement scored, blowout-over guard).

## Contracts (binding)
- **Staking:** $2 = 1 unit; 5⭐ = 2u; manual PASS/WATCH = 0u; automated CFB totals = 0u until an independent fair-total review, then 1u max; max 2u/bet, 4u/day, 10u/week; fan-team
  (Ohio State, Titans) capped 1u with case written first. Never resize
  mid-season.
- **Format:** locked in `weekly-output-format.md` — play leads in caps,
  stars, write-up per pick, game notes, tracking footer. Change only when
  David asks.
- **Selection:** The Tuesday CLV research cohort ranks full-game spreads,
  Moneylines, Overs, and Unders by price edge versus consensus (AQ-220;
  cents; units ≥1.5¢/≥2¢). User-facing Saturday NCAA and Sunday NFL picks run
  `cash-confidence.py --league ncaaf|nfl`: rank by consensus no-vig cash
  probability, keep the -250 ceiling, and retain one selection per game.
  Price edge is secondary on game-day boards. Manual QB/injury, weather, role,
  and movement review may
  lower confidence or mark WATCH/PASS, never inflate it.
- **Models:** NO validated edge — Elo, SRS, pace, cheap-EPA all lost their
  backtests. NFL cash confidence is a market-derived no-vig baseline, not an
  internal model. Research edges are price (best book, Pinnacle CLV), book
  disagreement, and situational flags (display-only until their own record
  earns weight).
- **Gates:** test-picks.py pre-flight blocks boards on stale odds (>6h),
  ambiguous team matches, phantom forecasts, ledger drift. NFL preseason is
  excluded. Never invent an NFL model total. Automated CFB totals also remain
  WATCH/0u until the manual team-score, ceiling, and garbage-time review passes.

## Commands (edge engine since 2026-10-02: `edge.py`, AQ-271)
- `edge.py status` — flags, beat-close %, paper units, real units, staking gate
- `edge.py flag` — runs every 30 min after the free pull (launchd); DK vs Pinnacle, spreads + moneylines, no totals, no confidence
- `edge.py close` · `edge.py settle` — run in the daily data loop; fill the Pinnacle close and the result
- Ledger: `edge-ledger.csv` (one row per game, first number wins). 0u until 100 flags; 1u only at ≥54% beat-close.
- Legacy (phase 2 archives it): `football.py status|board|check|settle|learn|bet` — still runs, no longer the pick process
- Free continuous lines: `fetch-free-lines.py` (Pinnacle guest API + DraftKings via ESPN, every 30 min via `com.davidos.football-free-lines`); merged into every board; closes within 75 min of kickoff land in snapshots.csv. Odds API credits (500/mo free) are for the 6-book consensus and nothing else.
- Legacy, research only: `run-weekly-card.py`, `weekly-picks.py`, `cash-confidence.py`, `slate.py --team X`, `calibration-report.py`
- Session: start a fresh session for football (AQ-157). Inputs are this packet and script stdout; grep instructions/model-notes, never Read them whole.

## Standing cautions
- Odds API quota rations (AQ-130 opt 1); three markets cost 3 credits per
  league-specific pull; staleness banner prints when >6h.
- CFB injuries underreported by nature; intl venues get no forecast + extra
  doubt; neutral sites get no home bump (the Dublin lesson).
""", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} chars)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
